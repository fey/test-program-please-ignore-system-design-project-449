-- Схема сервиса такси. Поездка хранит город и время завершения, потому что
-- отчёт по городам и дням строится по этим двум полям.
CREATE TABLE IF NOT EXISTS passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id BIGINT NOT NULL REFERENCES passengers (id),
    driver_id BIGINT REFERENCES drivers (id),
    status VARCHAR(32) NOT NULL DEFAULT 'searching'
        CHECK (status IN ('searching', 'accepted', 'in_progress', 'completed', 'cancelled')),
    city VARCHAR(64) NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    pickup_address VARCHAR(500) NOT NULL,
    destination_address VARCHAR(500) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ
);

-- История статусов поездки для чтения внутри сервиса. События для других
-- систем лежат в outbox, это отдельная таблица с другим назначением.
CREATE TABLE IF NOT EXISTS trip_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES trips (id),
    event VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
